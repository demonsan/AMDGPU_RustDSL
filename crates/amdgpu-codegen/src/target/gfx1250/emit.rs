//! gfx1250 assembly emission (G1). The instruction selection is the shared one (the MIR of `lower` / `regalloc`); this emitter spells it in the
//! gfx12 / gfx1250 assembler syntax: the gfx950 spelling of an instruction is re-spelled through a table checked against the node's
//! `llvm-mc -mcpu=gfx1250` (docs/gfx1250-plan.md), and the ops whose meaning differs on gfx1250 (the ABI registers, the waits, the barrier)
//! are emitted directly. Anything outside the table is a compile error naming the instruction, never a guess.

use crate::mir::*;
use crate::regalloc::Alloc;
use amdgpu_dsl::DType;

fn round_up(v: u32, m: u32) -> u32 {
    if m <= 1 {
        v
    } else {
        v.div_ceil(m) * m
    }
}

thread_local! {
    /// the verbatim instruction texts of the function being emitted (`RegHints::raw_texts`; `inst_lines` sees one instruction only)
    static RAW_TEXTS: std::cell::RefCell<Vec<String>> = const { std::cell::RefCell::new(Vec::new()) };
}

fn a_raw_text(k: i64) -> Result<String, String> {
    RAW_TEXTS.with(|r| r.borrow().get(k as usize).cloned()).ok_or_else(|| format!("raw instruction #{k}: no text"))
}

/// The gfx1250 assembly of an allocated function.
pub fn emit(m: &MFunction, a: &Alloc) -> Result<String, String> {
    emit_kd(m, a, &[])
}

/// The kernel-descriptor directives an exact kernel may set (`Function::kd`).
pub const KD_DIRECTIVES: &[&str] = &[
    "user_sgpr_kernarg_preload_length", "user_sgpr_kernarg_preload_offset", "inst_pref_size", "system_vgpr_workitem_id",
    "system_sgpr_workgroup_id_x", "system_sgpr_workgroup_id_y", "system_sgpr_workgroup_id_z", "next_free_vgpr", "next_free_sgpr",
    "memory_ordered", "forward_progress", "float_denorm_mode_32", "float_denorm_mode_16_64", "named_barrier_count", "round_robin_scheduling",
    "fp16_overflow", "group_segment_fixed_size", "kernarg_size",
    // not a descriptor field: the `s_code_end` words after the kernel's code (an exact replay's padding, as the author's toolchain wrote it)
    "code_end_pad",
    // a launch fact for the hang-safety verifier (workgroups per cluster; `gpu_verify_1250`): accepted, not a descriptor field, never printed
    "cluster_dims",
];

/// `emit` with the author's descriptor directives (`kd`) replacing the emitter's.
pub fn emit_kd(m: &MFunction, a: &Alloc, kd: &[(String, i64)]) -> Result<String, String> {
    for (k, _) in kd {
        if !KD_DIRECTIVES.contains(&k.as_str()) && !k.starts_with("g5:") {
            return Err(format!("{}: kernel-descriptor directive `{k}` is not settable (known: {})", m.name, KD_DIRECTIVES.join(", ")));
        }
    }
    let kdv = |k: &str| kd.iter().rev().find(|x| x.0 == k).map(|x| x.1);
    let t = &amdgpu_target::gfx1250::GFX1250;
    RAW_TEXTS.with(|r| *r.borrow_mut() = m.reg_hints.raw_texts.clone());
    if crate::regalloc::agpr_count(m, a) > 0 {
        return Err(format!("{}: gfx1250 has no AGPRs (the allocation used some)", m.name));
    }
    let mut out = String::new();
    out.push_str("// Generated by amdc (AMDGPU_RustDSL), target gfx1250. Do not edit.\n");
    out.push_str(".text\n");
    out.push_str(&format!(".globl {}\n", m.name));
    out.push_str(".p2align 8\n");
    out.push_str(&format!(".type {},@function\n", m.name));
    out.push_str(&format!("{}:\n", m.name));
    // the kernel prologue the gfx1250 assembler requires (s_mov_b64 / v_nop / global_prefetch_b8 first) and LLVM emits for every kernel, in
    // LLVM's form; s[6:7] is a reserved SGPR pair (never allocated), v0 the packed workitem ids (read only). Exact mode: the author's
    // instructions are the prologue (none added).
    if !m.exact {
        out.push_str("    s_setreg_imm32_b32 hwreg(HW_REG_WAVE_MODE, 25, 1), 1\n");
        out.push_str("    s_mov_b64 s[6:7], 0\n");
        out.push_str("    v_nop\n");
        out.push_str("    global_prefetch_b8 v0, s[6:7] scope:SCOPE_SE\n");
    }
    // the split-counter waits (gfx1250 waits.rs): the shared pass's waits re-expressed, plus XCNT
    // exact mode: the author's waits and padding are verified (check.rs), never added to
    let plan = if m.exact { super::waits::Plan::default() } else { super::waits::plan(m, a) };
    // the gfx1250 software hazards (hazards.rs); the shared pass's s_nop wait states are not needed on gfx1250 (all other VALU dependencies
    // interlock) and are dropped, except the author's in exact mode
    let hz = if m.exact { super::hazards::Plan::default() } else { super::hazards::plan(m, a) };
    // VGPRs above v255: the MSB window (msb.rs); 0 at every block start
    let windowed = a.max_v > 256 || m.blocks.iter().any(|b| b.insts.iter().any(|i| i.op == MOp::SSetVgprMsb));
    // (exact mode: the author's MSBs carry along the layout, as the author's code runs; the compiler's are 0 at every block start)
    let mut msb = super::msb::Msb::default();
    // exact mode: the author's block order (`Stmt::LayoutKey`); an unkeyed block stays right after the block before it
    let order: Vec<usize> = if m.exact && !m.reg_hints.layout_keys.is_empty() {
        let key: std::collections::HashMap<u32, u32> = m.reg_hints.layout_keys.iter().map(|(l, k)| (*l, *k)).collect();
        let mut cur = (0u32, 0u32);
        let mut ks: Vec<((u32, u32), usize)> = Vec::new();
        for (i, b) in m.blocks.iter().enumerate() {
            cur = match key.get(&b.label) {
                // (sub-key 1: an unkeyed block before it - the entry - stays first; the unkeyed blocks after it follow with 2, 3, ..)
                Some(k) => (*k, 1),
                None => (cur.0, cur.1 + 1),
            };
            ks.push((cur, i));
        }
        ks.sort_by_key(|x| x.0);
        ks.into_iter().map(|x| x.1).collect()
    } else {
        (0..m.blocks.len()).collect()
    };
    let keyed = order.len() == m.blocks.len() && m.exact && !m.reg_hints.layout_keys.is_empty();
    // keyed layout: blocks without instructions that only jump on are not laid out; every edge goes to its final block
    let thru: std::collections::HashMap<u32, u32> = if keyed {
        let has_key: std::collections::HashSet<u32> = m.reg_hints.author_branches.iter().copied().collect();
        m.blocks
            .iter()
            .filter_map(|b| match (&b.term, b.insts.is_empty() && !has_key.contains(&b.label)) {
                (Term::Goto(t), true) => Some((b.label, *t)),
                _ => None,
            })
            .collect()
    } else {
        Default::default()
    };
    let fin = |mut l: u32| {
        for _ in 0..64 {
            match thru.get(&l) {
                Some(&n) if n != l => l = n,
                _ => break,
            }
        }
        l
    };
    let order: Vec<usize> = order.into_iter().filter(|&i| !thru.contains_key(&m.blocks[i].label)).collect();
    let pos: std::collections::HashMap<u32, usize> = order.iter().enumerate().map(|(k, &i)| (m.blocks[i].label, k)).collect();
    // keyed layout: `A: if c goto T (backward); B: goto E (forward)` with B the author's branch-only block right after A and reached only
    // from A is the same control flow as the author's latch `A: if !c goto E; B: goto T` - written the author's way
    let mut latch_a: std::collections::HashMap<u32, (Pred, u32, u32)> = Default::default();
    let mut latch_b: std::collections::HashMap<u32, u32> = Default::default();
    // (the second shape: `A: if c goto B; else goto H (backward)` with B next, empty, `goto E` (forward; B may be a shared exit): the
    // author's `A: if c goto E; B: goto H`, every other edge into B going straight to E)
    let mut redirect: std::collections::HashMap<u32, u32> = Default::default();
    if keyed {
        let mut preds: std::collections::HashMap<u32, usize> = Default::default();
        for b in &m.blocks {
            match &b.term {
                Term::Goto(t) => *preds.entry(fin(*t)).or_default() += 1,
                Term::CondGoto { target, fall, .. } => {
                    *preds.entry(fin(*target)).or_default() += 1;
                    *preds.entry(fin(*fall)).or_default() += 1;
                }
                Term::Endpgm => {}
            }
        }
        for (k, &bi) in order.iter().enumerate() {
            let b = &m.blocks[bi];
            let Term::CondGoto { on, target, fall } = &b.term else { continue };
            let (tg, fl) = (fin(*target), fin(*fall));
            let Some(&nb) = order.get(k + 1) else { continue };
            let nbk = &m.blocks[nb];
            let keyed_b = m.reg_hints.layout_keys.iter().any(|(l, _)| *l == fl);
            let Term::Goto(e) = &nbk.term else { continue };
            let e = fin(*e);
            if tg == nbk.label && nbk.insts.is_empty() && keyed_b {
                let (pf, pe) = (pos.get(&fl).copied().unwrap_or(usize::MAX), pos.get(&e).copied().unwrap_or(0));
                if pf <= k && pe > k + 1 {
                    latch_a.insert(b.label, (*on, e, tg));
                    latch_b.insert(tg, fl);
                    redirect.insert(tg, e);
                }
                continue;
            }
            if fl != nbk.label || !nbk.insts.is_empty() || !keyed_b || preds.get(&fl) != Some(&1) {
                continue;
            }
            let Term::Goto(e) = &nbk.term else { continue };
            let e = fin(*e);
            let (pt, pe) = (pos.get(&tg).copied().unwrap_or(usize::MAX), pos.get(&e).copied().unwrap_or(0));
            if pt <= k && pe > k + 1 {
                let inv = match on {
                    Pred::Scc0 => Pred::Scc1,
                    Pred::Scc1 => Pred::Scc0,
                    Pred::Vccnz => Pred::Vccz,
                    Pred::Vccz => Pred::Vccnz,
                };
                latch_a.insert(b.label, (inv, e, fl));
                latch_b.insert(fl, tg);
            }
        }
    }
    for (oi, &bi) in order.iter().enumerate() {
        let b = &m.blocks[bi];
        let next_label = order.get(oi + 1).map(|&n| m.blocks[n].label);
        out.push_str(&format!("BB{}:\n", b.label));
        if !m.exact {
            msb = super::msb::Msb::default();
        }
        for (ii, inst) in b.insts.iter().enumerate() {
            let lines = match plan.replace.get(&(bi, ii)) {
                Some(r) => r.clone(),
                None if inst.op == MOp::SNop && !m.exact => Vec::new(),
                None => {
                    let mut v = plan.before.get(&(bi, ii)).cloned().unwrap_or_default();
                    v.extend(hz.before.get(&(bi, ii)).cloned().unwrap_or_default());
                    v.extend(inst_lines(a, inst).map_err(|e| format!("{}: block {}: {e}", m.name, b.label))?);
                    v
                }
            };
            let n_lines = lines.len();
            for (li, line) in lines.into_iter().enumerate() {
                let mut ls = if windowed { super::msb::window(&line, &mut msb, m.exact).map_err(|e| format!("{}: block {}: {e}", m.name, b.label))? } else { vec![line] };
                // the author's words for this instruction (exact replay): its line, checked by the window above, becomes their comment
                if let (Some(w), true) = (&inst.words, li + 1 == n_lines) {
                    if let Some(last) = ls.last_mut() {
                        *last = format!(".long {} // {}", w.iter().map(|x| format!("{x:#010x}")).collect::<Vec<_>>().join(", "), last.trim());
                    }
                }
                for l in ls {
                    out.push_str("    ");
                    out.push_str(&l);
                    out.push('\n');
                }
            }
        }
        if windowed && !m.exact && msb != super::msb::Msb::default() && !matches!(b.term, Term::Endpgm) {
            out.push_str("    s_set_vgpr_msb 0\n");
        }
        for line in plan.end.get(&bi).into_iter().flatten() {
            out.push_str(&format!("    {line}\n"));
        }

        let redir = |l: u32| redirect.get(&l).copied().unwrap_or(l);
        let term = match &b.term {
            // an author's latch block (only its branch) whose terms were swapped by the structure: see `latch` above
            Term::Goto(_) if latch_b.contains_key(&b.label) => Term::Goto(latch_b[&b.label]),
            Term::CondGoto { .. } if latch_a.contains_key(&b.label) => {
                let (p, e, f) = latch_a[&b.label];
                Term::CondGoto { on: p, target: e, fall: f }
            }
            Term::Goto(t) => Term::Goto(redir(fin(*t))),
            Term::CondGoto { on, target, fall } => {
                let (tg, fl) = (redir(fin(*target)), redir(fin(*fall)));
                if tg == fl {
                    Term::Goto(tg)
                } else {
                    Term::CondGoto { on: *on, target: tg, fall: fl }
                }
            }
            x => x.clone(),
        };
        match &term {
            Term::Goto(t) => {
                // (an author's block that is only its branch keeps it, even to the next block: the author wrote it)
                // (the author's own branch - `Stmt::Goto` - is written even to the next block)
                let only_branch = keyed && m.reg_hints.author_branches.contains(&b.label);
                if only_branch || !((m.elide_fallthrough || keyed) && next_label == Some(*t)) {
                    out.push_str(&format!("    s_branch BB{t}\n"))
                }
            }
            Term::CondGoto { on, target, fall } => {
                let br = match on {
                    Pred::Scc0 => "s_cbranch_scc0",
                    Pred::Scc1 => "s_cbranch_scc1",
                    Pred::Vccnz => "s_cbranch_vccnz",
                    Pred::Vccz => "s_cbranch_vccz",
                };
                // (keyed layout, neither side next: the conditional branch goes forward and the unconditional one back, as an author
                // writes a loop latch - `s_cbranch_<inv> exit; s_branch header`)
                let backward = |l: u32| pos.get(&l).map_or(false, |&p| p <= oi);
                let flip = keyed && next_label != Some(*target) && next_label != Some(*fall) && backward(*target) && !backward(*fall);
                if flip {
                    let inv = match on {
                        Pred::Scc0 => "s_cbranch_scc1",
                        Pred::Scc1 => "s_cbranch_scc0",
                        Pred::Vccnz => "s_cbranch_vccz",
                        Pred::Vccz => "s_cbranch_vccnz",
                    };
                    out.push_str(&format!("    {inv} BB{fall}\n"));
                    out.push_str(&format!("    s_branch BB{target}\n"));
                } else if keyed && next_label == Some(*target) && next_label != Some(*fall) {
                    // the author's layout puts the taken side next: the inverse branch to the other side, nothing else
                    let inv = match on {
                        Pred::Scc0 => "s_cbranch_scc1",
                        Pred::Scc1 => "s_cbranch_scc0",
                        Pred::Vccnz => "s_cbranch_vccz",
                        Pred::Vccz => "s_cbranch_vccnz",
                    };
                    out.push_str(&format!("    {inv} BB{fall}\n"));
                } else {
                    out.push_str(&format!("    {br} BB{target}\n"));
                    if !((m.elide_fallthrough || keyed) && next_label == Some(*fall)) {
                        out.push_str(&format!("    s_branch BB{fall}\n"));
                    }
                }
            }
            Term::Endpgm => out.push_str("    s_endpgm\n"),
        }
    }
    for _ in 0..kdv("code_end_pad").unwrap_or(0) {
        out.push_str("    s_code_end\n");
    }
    out.push_str(&format!(".size {}, .-{}\n", m.name, m.name));

    let vgpr = kdv("next_free_vgpr").map(|v| v as u32).unwrap_or_else(|| round_up(a.max_v.max(1), t.emit.vgpr_granule));
    let sgpr = kdv("next_free_sgpr").map(|v| v as u32).unwrap_or(a.max_s.max(1));
    let preload = kdv("user_sgpr_kernarg_preload_length").unwrap_or(0);
    let d = |k: &str, dflt: i64| kdv(k).unwrap_or(dflt);
    // (the kernel descriptor's alignment padding goes into .text; an exact replay pads with the author's s_code_end instead)
    out.push_str(if kdv("code_end_pad").is_some() { "\n" } else { "\n.p2align 6\n" });
    out.push_str(&format!(".amdhsa_kernel {}\n", m.name));
    out.push_str(&format!("    .amdhsa_group_segment_fixed_size {}\n", d("group_segment_fixed_size", m.lds_bytes as i64)));
    out.push_str("    .amdhsa_private_segment_fixed_size 0\n");
    out.push_str(&format!("    .amdhsa_kernarg_size {}\n", d("kernarg_size", round_up(m.kernarg_size, 8) as i64)));
    // the kernarg segment pointer in s[0:1] (then the preloaded kernarg dwords); the workgroup ids are architected (TTMP9 / TTMP7), the
    // workitem ids packed in v0
    out.push_str(&format!("    .amdhsa_user_sgpr_count {}\n", 2 + preload));
    out.push_str("    .amdhsa_user_sgpr_kernarg_segment_ptr 1\n");
    if preload > 0 {
        out.push_str(&format!("    .amdhsa_user_sgpr_kernarg_preload_length {preload}\n"));
        out.push_str(&format!("    .amdhsa_user_sgpr_kernarg_preload_offset {}\n", d("user_sgpr_kernarg_preload_offset", 0)));
    }
    out.push_str("    .amdhsa_wavefront_size32 1\n");
    for k in ["x", "y", "z"] {
        out.push_str(&format!("    .amdhsa_system_sgpr_workgroup_id_{k} {}\n", d(&format!("system_sgpr_workgroup_id_{k}"), 1)));
    }
    out.push_str(&format!("    .amdhsa_system_vgpr_workitem_id {}\n", d("system_vgpr_workitem_id", 2)));
    out.push_str(&format!("    .amdhsa_next_free_vgpr {vgpr}\n"));
    out.push_str(&format!("    .amdhsa_next_free_sgpr {sgpr}\n"));
    let named = m.blocks.iter().flat_map(|b| b.insts.iter()).filter_map(|i| match i.op {
        MOp::SBarrierInit | MOp::SBarrierJoin | MOp::SBarrierSignal | MOp::SBarrierWait => Some((i.imm & 0xffff) as i16 as i64),
        _ => None,
    }).filter(|id| *id > 0).max().unwrap_or(0);
    out.push_str(&format!("    .amdhsa_named_barrier_count {}\n", d("named_barrier_count", named)));
    let (d32, d64, _ieee) = m.fp_mode.unwrap_or((3, 3, false));
    out.push_str(&format!("    .amdhsa_float_denorm_mode_32 {}\n", d("float_denorm_mode_32", d32 as i64)));
    out.push_str(&format!("    .amdhsa_float_denorm_mode_16_64 {}\n", d("float_denorm_mode_16_64", d64 as i64)));
    for k in ["inst_pref_size", "memory_ordered", "forward_progress", "round_robin_scheduling", "fp16_overflow"] {
        if let Some(v) = kdv(k) {
            out.push_str(&format!("    .amdhsa_{k} {v}\n"));
        }
    }
    out.push_str(".end_amdhsa_kernel\n");

    out.push_str("\n.amdgpu_metadata\n---\namdhsa.kernels:\n");
    out.push_str(&format!("  - .name: {}\n", m.name));
    out.push_str(&format!("    .symbol: {}.kd\n", m.name));
    out.push_str(&format!("    .kernarg_segment_size: {}\n", round_up(m.kernarg_size, 8)));
    out.push_str("    .kernarg_segment_align: 8\n");
    out.push_str(&format!("    .group_segment_fixed_size: {}\n", m.lds_bytes));
    out.push_str("    .private_segment_fixed_size: 0\n");
    out.push_str(&format!("    .wavefront_size: {}\n", t.wave.lanes));
    out.push_str(&format!("    .max_flat_workgroup_size: {}\n", m.workgroup_size));
    out.push_str(&format!("    .sgpr_count: {sgpr}\n"));
    out.push_str(&format!("    .vgpr_count: {vgpr}\n"));
    out.push_str("    .sgpr_spill_count: 0\n");
    out.push_str("    .vgpr_spill_count: 0\n");
    out.push_str("    .args:\n");
    // every kernarg byte must be covered by an `.args` entry: the runtime copies a launch's arguments entry by entry (a word read only through
    // the kernarg preload, or skipped by the DSL's args, would otherwise arrive as garbage): gaps get by-value padding entries
    let ksize = round_up(m.kernarg_size.max(kdv("kernarg_size").unwrap_or(0) as u32), 4);
    let mut cover: Vec<(u32, u32)> = m.args.iter().map(|x| (x.offset, x.offset + x.size)).collect();
    cover.sort();
    let mut gaps = Vec::new();
    let mut at = 0u32;
    for (s, e) in &cover {
        if *s > at {
            gaps.push((at, *s));
        }
        at = at.max(*e);
    }
    if at < ksize {
        gaps.push((at, ksize));
    }
    for (k, (s, e)) in gaps.iter().enumerate() {
        out.push_str(&format!("      - .name: \"pad{k}\"\n        .offset: {s}\n        .size: {}\n        .value_kind: by_value\n", e - s));
    }
    for arg in &m.args {
        out.push_str(&format!("      - .name: \"{}\"\n", arg.name));
        out.push_str(&format!("        .offset: {}\n", arg.offset));
        out.push_str(&format!("        .size: {}\n", arg.size));
        match arg.dsl_ty {
            DType::Ptr => out.push_str("        .value_kind: global_buffer\n        .address_space: global\n"),
            DType::F32 => out.push_str("        .value_kind: by_value\n        .value_type: f32\n"),
            _ => out.push_str("        .value_kind: by_value\n        .value_type: i32\n"),
        }
    }
    out.push_str(&format!("amdhsa.target: amdgcn-amd-amdhsa--{}\n", t.name));
    out.push_str("amdhsa.version:\n  - 1\n  - 2\n...\n");
    out.push_str(".end_amdgpu_metadata\n");
    Ok(out)
}

/// The gfx1250 lines of one instruction.
pub fn inst_lines(a: &Alloc, inst: &MInst) -> Result<Vec<String>, String> {
    let d_s = || inst.dst.map(|r| format!("s{}", a.phys[r as usize])).unwrap_or_default();
    let d_v = || inst.dst.map(|r| format!("v{}", a.phys[r as usize])).unwrap_or_default();
    let lines = match inst.op {
        // the ABI registers: s[0:1] the kernarg segment pointer (user SGPRs); the workgroup ids are architected: x = TTMP9, y = TTMP7[15:0],
        // z = TTMP7[31:16] (no workgroup clusters in G1)
        // (the workgroup ids lower to SReadTtmp on gfx1250; s2.. hold the preloaded kernarg dwords: `Op::KernargPreload`)
        MOp::SReadPhys => {
            if inst.dst.map(|r| a.phys[r as usize] as i64) == Some(inst.imm) {
                vec![]
            } else {
                vec![format!("s_mov_b32 {}, s{}", d_s(), inst.imm)]
            }
        }
        // the workitem ids are packed in v0 (x = v0[9:0])
        MOp::VReadPhys => match inst.imm {
            0 => vec![format!("v_and_b32_e32 {}, 0x3ff, v0", d_v())],
            k => return Err(format!("v{k} is not an ABI register on gfx1250")),
        },
        // gfx950 vmcnt counts loads and stores, lgkmcnt LDS and scalar memory: a wait for n of them is a wait for n of each split counter
        // (at most n younger operations of the class remain, so the target operation has completed); conservative until G2's per-counter
        // scoreboard
        MOp::SWaitVm => vec![format!("s_wait_loadcnt {:#x}", inst.imm), format!("s_wait_storecnt {:#x}", inst.imm)],
        MOp::SWaitLgkm => vec![format!("s_wait_dscnt {:#x}", inst.imm), format!("s_wait_kmcnt {:#x}", inst.imm.min(31))],
        MOp::SWaitCnt => {
            let (vm, lg) = (inst.imm & 0xff, inst.imm >> 8);
            vec![
                format!("s_wait_loadcnt {vm:#x}"),
                format!("s_wait_storecnt {vm:#x}"),
                format!("s_wait_dscnt {lg:#x}"),
                format!("s_wait_kmcnt {:#x}", lg.min(31)),
            ]
        }
        // the split barrier of the workgroup (id -1)
        MOp::SBarrier => vec!["s_barrier_signal -1".to_string(), "s_barrier_wait -1".to_string()],
        MOp::SWaitTensor => vec![format!("s_wait_tensorcnt {:#x}", inst.imm)],
        // the gfx1250 V#: base [56:0], num_records [101:57] (bytes, 45 bits), stride 0, type 0 (buffer)
        MOp::SBufferRsrc | MOp::SBufferRsrcDyn => {
            let d = a.phys[inst.dst.ok_or("dst")? as usize];
            let src = |k: usize| -> Result<u32, String> {
                match inst.srcs.get(k) {
                    Some(Src::Reg(r)) => Ok(a.phys[*r as usize]),
                    _ => Err("buffer descriptor operand".into()),
                }
            };
            let b = src(0)?;
            let mut v = vec![format!("s_mov_b32 s{d}, s{b}"), format!("s_and_b32 s{}, s{}, 0x1ffffff", d + 1, b + 1)];
            if inst.op == MOp::SBufferRsrc {
                let n = inst.imm as u32 as u64;
                if n & 0x7f != 0 {
                    v.push(format!("s_or_b32 s{}, s{}, {:#x}", d + 1, d + 1, ((n & 0x7f) << 25) as u32));
                }
                v.push(format!("s_mov_b32 s{}, {:#x}", d + 2, (n >> 7) as u32));
            } else {
                let n = src(1)?;
                v.push(format!("s_lshl_b32 s{}, s{n}, 25", d + 3));
                v.push(format!("s_or_b32 s{}, s{}, s{}", d + 1, d + 1, d + 3));
                v.push(format!("s_lshr_b32 s{}, s{n}, 7", d + 2));
            }
            v.push(format!("s_mov_b32 s{}, 0", d + 3));
            v
        }
        MOp::SWaitCtr => {
            const MN: [&str; 7] = ["s_wait_loadcnt", "s_wait_storecnt", "s_wait_dscnt", "s_wait_kmcnt", "s_wait_xcnt", "s_wait_asynccnt", "s_wait_tensorcnt"];
            let c = (inst.imm >> 8) as usize;
            vec![format!("{} {:#x}", MN.get(c).ok_or("bad counter")?, inst.imm & 0xff)]
        }
        MOp::SBarrierSignal => vec![format!("s_barrier_signal {}", inst.imm)],
        MOp::SBarrierWait => vec![format!("s_barrier_wait {}", inst.imm)],
        MOp::SBarrierInit => vec![format!("s_mov_b32 m0, {:#x}", inst.imm), "s_barrier_init m0".to_string()],
        MOp::SBarrierJoin => vec![format!("s_barrier_join {}", inst.imm)],
        MOp::SSetSchedMode => vec![format!("s_setreg_imm32_b32 hwreg(HW_REG_WAVE_SCHED_MODE, 0, 2), {}", inst.imm)],
        MOp::SWaitAlu => vec![format!("s_wait_alu {:#x}", inst.imm)],
        MOp::SBarrierLeave => vec!["s_barrier_leave".to_string(), "s_wait_kmcnt 0x0".to_string()],
        // the cluster barrier (CDNA5 ISA section 5.6.6; LLVM's lowering): the first wave of each workgroup (isfirst on the workgroup barrier, SCC
        // via KMcnt, read after the wait) signals the cluster barrier; every wave waits on it
        MOp::SClusterBarrier => {
            use std::sync::atomic::{AtomicU64, Ordering};
            static N: AtomicU64 = AtomicU64::new(0);
            let l = format!(".Lcluster_bar_{}", N.fetch_add(1, Ordering::Relaxed));
            vec![
                "s_barrier_signal_isfirst -1".to_string(),
                "s_barrier_wait -1".to_string(),
                "s_wait_kmcnt 0x0".to_string(),
                format!("s_cbranch_scc0 {l}"),
                "s_barrier_signal -3".to_string(),
                format!("{l}:"),
                "s_barrier_wait -3".to_string(),
            ]
        }
        MOp::SSetVgprMsb => vec![format!("s_set_vgpr_msb {:#x}", inst.imm)],
        MOp::SReadTtmp => vec![format!("s_mov_b32 {}, ttmp{}", d_s(), inst.imm)],
        MOp::VWmmaF32_16x16x64Fp8
        | MOp::VWmmaF32_16x16x64Fp8Z
        | MOp::VWmmaF32_16x16x128Fp8
        | MOp::VWmmaF32_16x16x128Fp8Z
        | MOp::VWmmaScaleF32_32x16x128F4
        | MOp::VWmmaScaleF32_32x16x128F4Z => {
            let (mn, na, nb, nc, scaled, zero) = match inst.op {
                MOp::VWmmaF32_16x16x64Fp8 => ("v_wmma_f32_16x16x64_fp8_fp8", 8, 8, 8, false, false),
                MOp::VWmmaF32_16x16x64Fp8Z => ("v_wmma_f32_16x16x64_fp8_fp8", 8, 8, 8, false, true),
                MOp::VWmmaF32_16x16x128Fp8 => ("v_wmma_f32_16x16x128_fp8_fp8", 16, 16, 8, false, false),
                MOp::VWmmaF32_16x16x128Fp8Z => ("v_wmma_f32_16x16x128_fp8_fp8", 16, 16, 8, false, true),
                MOp::VWmmaScaleF32_32x16x128F4 => ("v_wmma_scale_f32_32x16x128_f4", 16, 8, 16, true, false),
                _ => ("v_wmma_scale_f32_32x16x128_f4", 16, 8, 16, true, true),
            };
            if inst.imm & 2 != 0 {
                // the author's words, verbatim (an exact replay)
                let w: Vec<String> = inst.srcs.iter().filter_map(|s| if let Src::Imm(x) = s { Some(format!("{:#010x}", *x as u32)) } else { None }).collect();
                return Ok(vec![format!(".long {} // {mn} (verbatim words)", w.join(", "))]);
            }
            let regs: Vec<u32> = inst.srcs.iter().filter_map(|s| if let Src::Reg(r) = s { Some(a.phys[*r as usize]) } else { None }).collect();
            let t = |p: u32, n: u32| format!("v[{}:{}]", p, p + n - 1);
            let d = a.phys[inst.dst.ok_or("wmma without a destination")? as usize];
            let mut ops = vec![t(d, nc), t(regs[0], na), t(regs[1], nb)];
            let mut k = 2;
            if zero {
                ops.push("0".to_string());
            } else {
                ops.push(t(regs[2], nc));
                k = 3;
            }
            if scaled {
                ops.push(format!("v{}", regs[k]));
                ops.push(format!("v{}", regs[k + 1]));
            }
            let mut l = format!("{mn} {}", ops.join(", "));
            if scaled && inst.imm & 1 != 0 {
                l.push_str(" matrix_b_scale:MATRIX_SCALE_ROW1");
            }
            vec![l]
        }
        MOp::SAddCoI32 | MOp::SSubCoI32 | MOp::SBfeU32 | MOp::SBitset0 | MOp::SBitset1 | MOp::SAddNcU64 | MOp::SMovB64Pair => {
            let s = |x: &Src| -> Result<String, String> {
                match x {
                    Src::Reg(r) => {
                        let p = a.phys[*r as usize];
                        Ok(if matches!(inst.op, MOp::SAddNcU64 | MOp::SMovB64Pair) { format!("s[{}:{}]", p, p + 1) } else { sgpr_name(p) })
                    }
                    Src::Imm(k) => Ok(format!("{:#x}", *k as u32)),
                    _ => Err("scalar form: register or constant operands".into()),
                }
            };
            let d = a.phys[inst.dst.ok_or("scalar form without a destination")? as usize];
            let dn = if matches!(inst.op, MOp::SAddNcU64 | MOp::SMovB64Pair) { format!("s[{}:{}]", d, d + 1) } else { format!("s{d}") };
            let mn = crate::op_attrs::attrs(inst.op).mnemonic;
            match inst.op {
                // in place on the destination (= a's register): only the bit operand is written
                MOp::SBitset0 | MOp::SBitset1 => vec![format!("{mn} {dn}, {}", s(&inst.srcs[1])?)],
                MOp::SMovB64Pair => vec![format!("{mn} {dn}, {}", s(&inst.srcs[0])?)],
                _ => vec![format!("{mn} {dn}, {}, {}", s(&inst.srcs[0])?, s(&inst.srcs[1])?)],
            }
        }
        MOp::VNop => vec!["v_nop".to_string()],
        MOp::VCvtPkFp8F32Half => {
            let p = |s: &Src| -> String {
                match s {
                    Src::Reg(r) if a.scalar.get(*r as usize).copied().unwrap_or(false) => sgpr_name(a.phys[*r as usize]),
                    Src::Reg(r) => format!("v{}", a.phys[*r as usize]),
                    Src::Imm(k) => format!("{:#x}", *k as u32),
                    _ => "?".into(),
                }
            };
            let d = a.phys[inst.dst.ok_or("v_cvt_pk_fp8_f32 without a destination")? as usize];
            let hi = inst.imm & 1 != 0;
            let n = inst.srcs.len();
            vec![format!("v_cvt_pk_fp8_f32 v{d}.{}, {}, {}{}", if hi { "h" } else { "l" }, p(&inst.srcs[n - 2]), p(&inst.srcs[n - 1]), if hi { " op_sel:[0,0,1]" } else { "" })]
        }
        MOp::VAddNcI32 | MOp::VSubrevU32 | MOp::VRcpIflagF32 | MOp::VAddNcU64 | MOp::GlobalLoadAsyncLds | MOp::SBufferLoadB32 => {
            let wide = inst.op == MOp::VAddNcU64;
            let v = |x: &Src, pair: bool| -> String {
                match x {
                    Src::Reg(r) => {
                        let p = a.phys[*r as usize];
                        if a.scalar.get(*r as usize).copied().unwrap_or(false) {
                            if pair { format!("s[{}:{}]", p, p + 1) } else { sgpr_name(p) }
                        } else if pair {
                            format!("v[{}:{}]", p, p + 1)
                        } else {
                            format!("v{p}")
                        }
                    }
                    Src::Imm(k) => format!("{:#x}", *k as u32),
                    _ => "?".into(),
                }
            };
            let mn = crate::op_attrs::attrs(inst.op).mnemonic;
            let line = match inst.op {
                MOp::GlobalLoadAsyncLds => {
                    let off = if inst.imm != 0 { format!(" offset:{}", inst.imm) } else { String::new() };
                    format!("{mn} {}, {}, off{off}", v(&inst.srcs[0], false), v(&inst.srcs[1], true))
                }
                MOp::SBufferLoadB32 => {
                    let d = a.phys[inst.dst.ok_or("s_buffer_load without a destination")? as usize];
                    let rs = match inst.srcs[0] { Src::Reg(r) => a.phys[r as usize], _ => 0 };
                    format!("{mn} s{d}, s[{}:{}], {} offset:{:#x}", rs, rs + 3, v(&inst.srcs[1], false), inst.imm)
                }
                _ => {
                    let d = a.phys[inst.dst.ok_or("VALU form without a destination")? as usize];
                    let dn = if wide { format!("v[{}:{}]", d, d + 1) } else { format!("v{d}") };
                    let ops: Vec<String> = inst.srcs.iter().map(|s| v(s, wide)).collect();
                    format!("{mn} {dn}, {}", ops.join(", "))
                }
            };
            vec![line]
        }
        MOp::SExecFromMask | MOp::SExecSelect => {
            let s = |x: &Src| -> String {
                match x {
                    Src::Reg(r) => {
                        let p = a.phys[*r as usize];
                        if p == crate::mir::VCC_PIN { "vcc_lo".to_string() } else { sgpr_name(p) }
                    }
                    Src::Imm(k) => format!("{:#x}", *k as u32),
                    _ => "?".to_string(),
                }
            };
            if inst.op == MOp::SExecFromMask {
                vec![format!("s_mov_b32 exec_lo, {}", s(&inst.srcs[0]))]
            } else {
                vec![format!("s_cselect_b32 exec_lo, {}, {}", s(&inst.srcs[1]), s(&inst.srcs[2]))]
            }
        }
        MOp::SSys | MOp::SSysVal => {
            let (op, k, k2) = (inst.imm & 0xff, ((inst.imm >> 8) & 0xffff) as u32, ((inst.imm >> 24) & 0xffff_ffff) as u32);
            let hw = |s: u32| format!("hwreg({}, {}, {})", s & 0x3f, (s >> 6) & 0x1f, ((s >> 11) & 0x1f) + 1);
            let regs: Vec<u32> = inst.srcs.iter().filter_map(|s| if let Src::Reg(r) = s { Some(a.phys[*r as usize]) } else { None }).collect();
            let line = if inst.op == MOp::SSysVal {
                let d = a.phys[inst.dst.ok_or("a wave-state read without a destination")? as usize];
                match op {
                    0 => format!("s_getreg_b32 s{d}, {}", hw(k)),
                    _ => format!("s_get_pc_i64 s[{}:{}]", d, d + 1),
                }
            } else {
                match op {
                    0 => format!("s_version {k:#x}"),
                    1 => format!("s_setreg_imm32_b32 {}, {k2:#x}", hw(k)),
                    2 => "s_wait_idle".to_string(),
                    3 => format!("s_prefetch_inst s[{}:{}], {k:#x}, s{}, {k2}", regs[0], regs[0] + 1, regs[1]),
                    5 => "v_nop".to_string(),
                    6 => format!("s_sleep {k}"),
                    _ => format!("global_prefetch_b8 v{}, s[{}:{}]{}", regs[0], regs[1], regs[1] + 1, if k != 0 { format!(" offset:{k}") } else { String::new() }),
                }
            };
            vec![line]
        }
        MOp::VSwapB32 => {
            let r: Vec<u32> = inst.srcs.iter().filter_map(|s| if let Src::Reg(r) = s { Some(a.phys[*r as usize]) } else { None }).collect();
            if r.len() != 2 {
                return Err("v_swap_b32: two register operands".into());
            }
            vec![format!("v_swap_b32 v{}, v{}", r[0], r[1])]
        }
        // exact mode: the author's instruction, verbatim
        // (an empty text: the ghost definition of a register the previous verbatim instruction wrote too; no line)
        MOp::RawInst => {
            let x = a_raw_text(inst.imm)?;
            if x.is_empty() {
                vec![]
            } else {
                vec![x]
            }
        }
        MOp::TensorLoadToLds | MOp::TensorStoreFromLds => {
            let mn = if inst.op == MOp::TensorLoadToLds { "tensor_load_to_lds" } else { "tensor_store_from_lds" };
            let regs: Vec<u32> = inst.srcs.iter().filter_map(|s| if let Src::Reg(r) = s { Some(a.phys[*r as usize]) } else { None }).collect();
            if inst.imm & crate::lower::RAW_TDM != 0 {
                // the author's / another assembler's words, verbatim (an exact replay)
                let w: Vec<String> = inst.srcs.iter().filter_map(|s| if let Src::Imm(x) = s { Some(format!("{:#010x}", *x as u32)) } else { None }).collect();
                vec![format!(".long {} // {mn} (verbatim words)", w.join(", "))]
            } else {
                let g = |r: u32, n: u32| format!("s[{}:{}]", r, r + n - 1);
                let mut ops = vec![g(regs[0], 4), g(regs[1], 8)];
                if regs.len() == 4 {
                    ops.push(g(regs[2], 4));
                    ops.push(g(regs[3], 4));
                }
                const TH: [&str; 8] = ["", "TH_LOAD_NT", "TH_LOAD_HT", "TH_LOAD_BYPASS", "TH_LOAD_LU", "TH_LOAD_NT_RT", "TH_LOAD_RT_NT", "TH_LOAD_NT_HT"];
                const TH_ST: [&str; 8] = ["", "TH_STORE_NT", "TH_STORE_HT", "TH_STORE_BYPASS", "TH_STORE_LU", "TH_STORE_NT_RT", "TH_STORE_RT_NT", "TH_STORE_NT_HT"];
                const SCOPE: [&str; 4] = ["", "SCOPE_SE", "SCOPE_DEV", "SCOPE_SYS"];
                let th = (inst.imm & 7) as usize;
                let scope = ((inst.imm >> 3) & 3) as usize;
                let mut l = format!("{mn} {}", ops.join(", "));
                if th != 0 {
                    l.push_str(&format!(" th:{}", if inst.op == MOp::TensorLoadToLds { TH[th] } else { TH_ST[th] }));
                }
                if scope != 0 {
                    l.push_str(&format!(" scope:{}", SCOPE[scope]));
                }
                if inst.imm & 32 != 0 {
                    l.push_str(" nv");
                }
                vec![l]
            }
        }
        _ => {
            let mut v = Vec::new();
            for l in crate::target::gfx950::emit::inst_lines(a, inst) {
                // (the XCNT waits: waits.rs)
                v.extend(respell(&l)?);
            }
            v
        }
    };
    Ok(lines)
}

