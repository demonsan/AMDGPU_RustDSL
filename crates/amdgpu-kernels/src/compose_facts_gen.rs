//! The source of `amdgpu_graph::compose_facts` (docs/compose.md): the CTA shape and rings every kernel's plan declares, generated from the kernels themselves (`amdc compose-facts --out FILE`;
//! `tests/compose_facts.rs` checks the checked-in file against it).

use crate::{reachable, registry};
use std::collections::BTreeSet;

pub fn source() -> String {
    let mut names: BTreeSet<String> = reachable::manifest_names();
    names.extend(registry::kernel_names().iter().map(|s| s.to_string()));
    let mut rows = Vec::new();
    for n in &names {
        let Some(f) = registry::kernel_by_name(n) else { continue };
        let Some(p) = &f.plan else { continue };
        let Some(c) = &p.cta else { continue };
        let rings: Vec<String> = p
            .rings
            .iter()
            .map(|r| format!("RingFact {{ name: {:?}, slots: {}, bytes_per_slot: {}, wave_private: {} }}", r.name, r.slots, r.bytes_per_slot, r.owner == amdgpu_dsl::plan::RingOwner::Wave))
            .collect();
        rows.push(format!("    KernelFacts {{ kernel: {:?}, threads: {}, waves: {}, phases: {}, units: {}, rings: &[{}] }},", n, c.threads, c.waves, p.phases.len(), p.units.len(), rings.join(", ")));
    }
    format!(
        "//! GENERATED by `amdc compose-facts --out crates/amdgpu-graph/src/compose_facts.rs` (crates/amdgpu-kernels/src/compose_facts_gen.rs): the CTA shape and rings of every kernel that declares a plan.\n\nuse crate::compose::{{KernelFacts, RingFact}};\n\npub static FACTS: &[KernelFacts] = &[\n{}\n];\n",
        rows.join("\n")
    )
}