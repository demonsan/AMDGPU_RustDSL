//! gfx950 assembly emission.
//!
//! Output is text consumed by the ROCm assembler (`clang -x assembler
//! -target amdgcn-amd-amdhsa -mcpu=gfx950`). Emitting text keeps the encoder in
//! LLVM's hands while every register, instruction and ordering decision stays
//! in this compiler.

use crate::mir::*;
use crate::regalloc::Alloc;
use amdgpu_dsl::DType;

pub fn emit(m: &MFunction, a: &Alloc) -> String {
    let mut out = String::new();
    out.push_str("// Generated by amdc (AMDGPU_RustDSL). Do not edit.\n");
    out.push_str(".text\n");
    out.push_str(&format!(".globl {}\n", m.name));
    out.push_str(".p2align 8\n");
    out.push_str(&format!(".type {},@function\n", m.name));
    out.push_str(&format!("{}:\n", m.name));

    for (bi, b) in m.blocks.iter().enumerate() {
        let next_label = m.blocks.get(bi + 1).map(|n| n.label);
        if let Some(a) = crate::backend::llvm_mir::loop_align() {
            if m.loops.iter().any(|l| l.0 == b.label) {
                out.push_str(&format!("    .p2align {}\n", a.trailing_zeros()));
            }
        }
        out.push_str(&format!("BB{}:\n", b.label));
        for inst in &b.insts {
            for line in inst_lines(a, inst) {
                out.push_str("    ");
                out.push_str(&line);
                out.push('\n');
            }
        }
        match &b.term {
            Term::Goto(t) => {
                if !(m.elide_fallthrough && next_label == Some(*t)) {
                    out.push_str(&format!("    s_branch BB{t}\n"))
                }
            }
            Term::CondGoto { on, target, fall } => {
                out.push_str(&format!("    {} BB{}\n", pred_mnemonic(*on), target));
                if !(m.elide_fallthrough && next_label == Some(*fall)) {
                    out.push_str(&format!("    s_branch BB{fall}\n"));
                }
            }
            Term::Endpgm => out.push_str("    s_endpgm\n"),
        }
    }

    out.push_str(&format!(".size {}, .-{}\n", m.name, m.name));

    let vgpr = round_up(a.max_v, 4).max(4);
    let sgpr = round_up(a.max_s, 8).max(8);

    // The kernel descriptor is a fixed 64-byte record and the runtime requires
    // it to be 64-byte aligned; without this the fields are read shifted and
    // the dispatch executes garbage.
    out.push_str("\n.p2align 6\n");
    out.push_str(&format!(".amdhsa_kernel {}\n", m.name));
    out.push_str(&format!("    .amdhsa_group_segment_fixed_size {}\n", m.lds_bytes));
    out.push_str("    .amdhsa_private_segment_fixed_size 0\n");
    // The kernarg segment size must be 8-byte aligned or the assembler rejects
    // the metadata outright.
    let kernarg = round_up(m.kernarg_size, 8);
    out.push_str(&format!("    .amdhsa_kernarg_size {}\n", kernarg));
    // Two user SGPRs: the kernarg segment pointer in s[0:1]. Without this
    // count the runtime passes no user SGPRs and every argument load reads
    // garbage.
    out.push_str("    .amdhsa_user_sgpr_count 2\n");
    out.push_str("    .amdhsa_user_sgpr_kernarg_segment_ptr 1\n");
    out.push_str("    .amdhsa_system_sgpr_workgroup_id_x 1\n");
    out.push_str("    .amdhsa_system_sgpr_workgroup_id_y 1\n");
    out.push_str("    .amdhsa_system_sgpr_workgroup_id_z 1\n");
    out.push_str("    .amdhsa_system_vgpr_workitem_id 0\n");
    out.push_str(&format!("    .amdhsa_next_free_vgpr {}\n", vgpr));
    out.push_str(&format!("    .amdhsa_next_free_sgpr {}\n", sgpr));
    out.push_str(&format!("    .amdhsa_accum_offset {}\n", vgpr));
    out.push_str("    .amdhsa_float_denorm_mode_32 3\n");
    out.push_str("    .amdhsa_float_denorm_mode_16_64 3\n");
    out.push_str("    .amdhsa_ieee_mode 0\n");
    out.push_str(".end_amdhsa_kernel\n");

    out.push_str("\n.amdgpu_metadata\n---\namdhsa.kernels:\n");
    out.push_str(&format!("  - .name: {}\n", m.name));
    out.push_str(&format!("    .symbol: {}.kd\n", m.name));
    out.push_str(&format!("    .kernarg_segment_size: {}\n", round_up(m.kernarg_size, 8)));
    out.push_str("    .kernarg_segment_align: 8\n");
    out.push_str(&format!("    .group_segment_fixed_size: {}\n", m.lds_bytes));
    out.push_str("    .private_segment_fixed_size: 0\n");
    out.push_str("    .wavefront_size: 64\n");
    out.push_str("    .max_flat_workgroup_size: ");
    out.push_str(&m.workgroup_size.to_string());
    out.push('\n');
    out.push_str(&format!("    .sgpr_count: {}\n", sgpr));
    out.push_str(&format!("    .vgpr_count: {}\n", vgpr));
    out.push_str("    .sgpr_spill_count: 0\n");
    out.push_str("    .vgpr_spill_count: 0\n");
    out.push_str("    .args:\n");
    for arg in &m.args {
        out.push_str(&format!("      - .name: \"{}\"\n", arg.name));
        out.push_str(&format!("        .offset: {}\n", arg.offset));
        out.push_str(&format!("        .size: {}\n", arg.size));
        match arg.dsl_ty {
            DType::Ptr => {
                out.push_str("        .value_kind: global_buffer\n");
                out.push_str("        .address_space: global\n");
            }
            DType::F32 => {
                out.push_str("        .value_kind: by_value\n");
                out.push_str("        .value_type: f32\n");
            }
            _ => {
                out.push_str("        .value_kind: by_value\n");
                out.push_str("        .value_type: i32\n");
            }
        }
    }
    out.push_str("amdhsa.target: amdgcn-amd-amdhsa--gfx950\n");
    out.push_str("amdhsa.version:\n  - 1\n  - 0\n...\n");
    out.push_str(".end_amdgpu_metadata\n");
    out
}

fn round_up(v: u32, m: u32) -> u32 {
    if m == 0 {
        v
    } else {
        ((v + m - 1) / m) * m
    }
}

fn pred_mnemonic(p: Pred) -> &'static str {
    match p {
        Pred::Scc0 => "s_cbranch_scc0",
        Pred::Scc1 => "s_cbranch_scc1",
        Pred::Vccnz => "s_cbranch_vccnz",
        Pred::Vccz => "s_cbranch_vccz",
    }
}

fn v(a: &Alloc, r: VReg) -> u32 {
    a.phys[r as usize]
}

fn vr(a: &Alloc, r: VReg) -> String {
    format!("v{}", v(a, r))
}

fn pair(a: &Alloc, r: VReg) -> String {
    let b = v(a, r);
    format!("v[{b}:{}]", b + 1)
}

/// A register tuple of `n` consecutive dwords, e.g. `v[8:9]` or `v[4:7]`.
fn tuple(a: &Alloc, r: VReg, n: u32) -> String {
    let b = v(a, r);
    format!("v[{b}:{}]", b + n - 1)
}

fn sr(a: &Alloc, r: VReg) -> String {
    format!("s{}", a.phys[r as usize])
}

fn spair(a: &Alloc, r: VReg) -> String {
    let b = a.phys[r as usize];
    format!("s[{b}:{}]", b + 1)
}

fn src1(a: &Alloc, s: Src) -> String {
    match s {
        Src::Reg(r) => vr(a, r),
        Src::Imm(i) => format!("{}", i as i32),
    }
}

fn src1_s(a: &Alloc, s: Src) -> String {
    match s {
        Src::Reg(r) => sr(a, r),
        Src::Imm(i) => format!("{i}"),
    }
}

fn mem_op(a: &Alloc, base: Src, off: i64) -> String {
    let p = match base {
        Src::Reg(r) => pair(a, r),
        Src::Imm(_) => "v[0:1]".to_string(),
    };
    if off == 0 {
        format!("{p}, off")
    } else {
        format!("{p}, off offset:{off}")
    }
}

fn inst_lines(a: &Alloc, inst: &MInst) -> Vec<String> {
    let d = |a: &Alloc| vr(a, inst.dst.expect("dst"));
    match inst.op {
        MOp::VMovB32 => {
            // A register-to-register move carries its source in `srcs`; a
            // constant carries its 32-bit pattern in `imm`.
            let text = match inst.srcs.first() {
                Some(s) => src1(a, *s),
                None => format!("{}", inst.imm as i32),
            };
            vec![format!("v_mov_b32_e32 {}, {}", d(a), text)]
        }
        MOp::VMovFromS => vec![format!("v_mov_b32_e32 {}, {}", d(a), sr(a, reg_of(&inst.srcs[0])))],
        MOp::VMovFromSPair => {
            let s = reg_of(&inst.srcs[0]);
            let b = a.phys[inst.dst.unwrap() as usize];
            let sb = a.phys[s as usize];
            vec![
                format!("v_mov_b32_e32 v{b}, s{sb}"),
                format!("v_mov_b32_e32 v{}, s{}", b + 1, sb + 1),
            ]
        }
        MOp::VPtrAdd => {
            let base = reg_of(&inst.srcs[0]);
            let off = inst.srcs[1];
            let bb = a.phys[base as usize];
            let db = a.phys[inst.dst.unwrap() as usize];
            vec![
                format!("v_add_co_u32 v{db}, vcc, v{bb}, {}", src1(a, off)),
                format!("v_addc_co_u32 v{}, vcc, v{}, 0, vcc", db + 1, bb + 1),
            ]
        }
        MOp::VReadPhys => vec![format!("v_mov_b32_e32 {}, v{}", d(a), inst.imm)],
        MOp::VAddU32 => bin(a, inst, "v_add_u32_e32"),
        MOp::VAddCoU32 => vec![format!(
            "v_add_co_u32 {}, vcc, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VAddcCoU32 => vec![format!(
            "v_addc_co_u32 {}, vcc, {}, {}, vcc",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VAddF32 => bin(a, inst, "v_add_f32_e32"),
        MOp::VSubF32 => bin(a, inst, "v_sub_f32_e32"),
        MOp::VMulF32 => bin(a, inst, "v_mul_f32_e32"),
        MOp::VMaxF32 => bin(a, inst, "v_max_f32_e32"),
        MOp::VCvtPknormU16 => vec![format!(
            "v_cvt_pknorm_u16_f32 {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VCvtPkFp8F32 => vec![format!(
            "v_cvt_pk_fp8_f32 {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VCvtPkBf16F32 => vec![format!(
            "v_cvt_pk_bf16_f32 {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VCvtPkFp8Lo => vec![format!(
            "v_cvt_scalef32_pk_fp8_bf16 {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VCvtPkFp8Hi => vec![format!(
            "v_cvt_scalef32_pk_fp8_bf16 {}, {}, {} op_sel:[0,0,1]",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VCvtPkFp8F32Hi => vec![format!(
            "v_cvt_pk_fp8_f32 {}, {}, {} op_sel:[0,0,1]",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VPermlane32Swap => vec![format!(
            "v_permlane32_swap_b32_e32 {}, {}",
            vr(a, reg_of(&inst.srcs[0])),
            vr(a, reg_of(&inst.srcs[1]))
        )],
        MOp::VPkAddF32 => vec![format!(
            "v_pk_add_f32 {}, {}, {}",
            pair(a, inst.dst.unwrap()),
            pair(a, reg_of(&inst.srcs[0])),
            pair(a, reg_of(&inst.srcs[1]))
        )],
        MOp::VPkMulF32 => vec![format!(
            "v_pk_mul_f32 {}, {}, {}",
            pair(a, inst.dst.unwrap()),
            pair(a, reg_of(&inst.srcs[0])),
            pair(a, reg_of(&inst.srcs[1]))
        )],
        MOp::VPkSubU16 => vec![format!(
            "v_pk_sub_u16 {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VPermB32 => vec![format!(
            "v_perm_b32 {}, {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1]),
            src1(a, inst.srcs[2])
        )],
        MOp::VMax3F32 => vec![format!(
            "v_max3_f32 {}, {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1]),
            src1(a, inst.srcs[2])
        )],
        MOp::VFmaF32 => vec![format!(
            "v_fma_f32 {}, {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1]),
            src1(a, inst.srcs[2])
        )],
        MOp::VExpF32 => un(a, inst, "v_exp_f32_e32"),
        MOp::VRcpF32 => un(a, inst, "v_rcp_f32_e32"),
        MOp::VCvtF32F16 => un(a, inst, "v_cvt_f32_f16_e32"),
        MOp::VCvtF16F32 => un(a, inst, "v_cvt_f16_f32_e32"),
        MOp::VAndB32 => bin(a, inst, "v_and_b32_e32"),
        MOp::VOrB32 => bin(a, inst, "v_or_b32_e32"),
        MOp::VXorB32 => bin(a, inst, "v_xor_b32_e32"),
        MOp::VLshlB32 => vec![format!(
            "v_lshlrev_b32_e32 {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VLshrB32 => vec![format!(
            "v_lshrrev_b32_e32 {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VMulLoU32 => vec![format!(
            "v_mul_lo_u32 {}, {}, {}",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VCmpLtI32 => cmp(a, inst, "v_cmp_lt_i32_e32"),
        MOp::VCmpGeI32 => cmp(a, inst, "v_cmp_ge_i32_e32"),
        MOp::VCmpNeI32 => cmp(a, inst, "v_cmp_ne_i32_e32"),
        MOp::VCmpLtF32 => cmp(a, inst, "v_cmp_lt_f32_e32"),
        MOp::VCndmask => vec![format!(
            "v_cndmask_b32_e32 {}, {}, {}, vcc",
            d(a),
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1])
        )],
        MOp::VWriteSub => {
            // Write one dword of a register tuple.
            let base = v(a, inst.dst.expect("dst"));
            vec![format!(
                "v_mov_b32_e32 v{}, {}",
                base + inst.imm as u32,
                src1(a, inst.srcs[0])
            )]
        }
        MOp::VReadSub => {
            let src = reg_of(&inst.srcs[0]);
            let base = v(a, src);
            vec![format!("v_mov_b32_e32 {}, v{}", d(a), base + inst.imm as u32)]
        }
        MOp::VMfma32x32x8F16 => {
            // 32x32x8 f16: D is sixteen dwords, A and B two each.
            let a_reg = reg_of(&inst.srcs[0]);
            let b_reg = reg_of(&inst.srcs[1]);
            let c_reg = reg_of(&inst.srcs[2]);
            vec![format!(
                "v_mfma_f32_32x32x8_f16 {}, {}, {}, {}",
                tuple(a, inst.dst.expect("dst"), 16),
                tuple(a, a_reg, 2),
                tuple(a, b_reg, 2),
                tuple(a, c_reg, 16)
            )]
        }
        MOp::VMfma32x32x8F16Z => {
            let a_reg = reg_of(&inst.srcs[0]);
            let b_reg = reg_of(&inst.srcs[1]);
            vec![format!(
                "v_mfma_f32_32x32x8_f16 {}, {}, {}, 0",
                tuple(a, inst.dst.expect("dst"), 16),
                tuple(a, a_reg, 2),
                tuple(a, b_reg, 2)
            )]
        }
        MOp::VMfmaScale32x32x64Fp8Z => {
            let a_reg = reg_of(&inst.srcs[0]);
            let b_reg = reg_of(&inst.srcs[1]);
            let sa = reg_of(&inst.srcs[2]);
            let sb = reg_of(&inst.srcs[3]);
            vec![format!(
                "v_mfma_scale_f32_32x32x64_f8f6f4 {}, {}, {}, 0, {}, {}",
                tuple(a, inst.dst.expect("dst"), 16),
                tuple(a, a_reg, 8),
                tuple(a, b_reg, 8),
                vr(a, sa),
                vr(a, sb)
            )]
        }
        MOp::VMfmaScale32x32x64Fp8 => {
            let a_reg = reg_of(&inst.srcs[0]);
            let b_reg = reg_of(&inst.srcs[1]);
            let c_reg = reg_of(&inst.srcs[2]);
            let sa = reg_of(&inst.srcs[3]);
            let sb = reg_of(&inst.srcs[4]);
            vec![format!(
                "v_mfma_scale_f32_32x32x64_f8f6f4 {}, {}, {}, {}, {}, {}",
                tuple(a, inst.dst.expect("dst"), 16),
                tuple(a, a_reg, 8),
                tuple(a, b_reg, 8),
                tuple(a, c_reg, 16),
                vr(a, sa),
                vr(a, sb)
            )]
        }
        MOp::VMfma16x16x32Fp8 => {
            let a_reg = reg_of(&inst.srcs[0]);
            let b_reg = reg_of(&inst.srcs[1]);
            let c_reg = reg_of(&inst.srcs[2]);
            vec![format!(
                "v_mfma_f32_16x16x32_fp8_fp8 {}, {}, {}, {}",
                tuple(a, inst.dst.expect("dst"), 4),
                tuple(a, a_reg, 2),
                tuple(a, b_reg, 2),
                tuple(a, c_reg, 4)
            )]
        }
        MOp::VMfma32x32x16Fp8 => {
            let a_reg = reg_of(&inst.srcs[0]);
            let b_reg = reg_of(&inst.srcs[1]);
            let c_reg = reg_of(&inst.srcs[2]);
            vec![format!(
                "v_mfma_f32_32x32x16_fp8_fp8 {}, {}, {}, {}",
                tuple(a, inst.dst.expect("dst"), 16),
                tuple(a, a_reg, 2),
                tuple(a, b_reg, 2),
                tuple(a, c_reg, 16)
            )]
        }
        MOp::VMfma16x16x16F16 => {
            // 16x16x16 f16: D is four dwords, A and B two each, C four.
            let a_reg = reg_of(&inst.srcs[0]);
            let b_reg = reg_of(&inst.srcs[1]);
            let c_reg = reg_of(&inst.srcs[2]);
            vec![format!(
                "v_mfma_f32_16x16x16_f16 {}, {}, {}, {}",
                tuple(a, inst.dst.expect("dst"), 4),
                tuple(a, a_reg, 2),
                tuple(a, b_reg, 2),
                tuple(a, c_reg, 4)
            )]
        }
        MOp::GlobalLoadU16 => vec![format!(
            "global_load_ushort {}, {}",
            d(a),
            mem_op(a, inst.srcs[0], inst.imm)
        )],
        MOp::GlobalLoadF32 => vec![format!(
            "global_load_dword {}, {}",
            d(a),
            mem_op(a, inst.srcs[0], inst.imm)
        )],
        MOp::GlobalLoadB128S => vec![format!(
            "global_load_dwordx4 {}, {}, {}{}",
            tuple(a, inst.dst.expect("dst"), 4),
            vr(a, reg_of(&inst.srcs[1])),
            spair(a, reg_of(&inst.srcs[0])),
            if inst.imm == 0 { String::new() } else { format!(" offset:{}", inst.imm) }
        )],
        MOp::GlobalLoadF32S => vec![format!(
            "global_load_dword {}, {}, {}{}",
            d(a),
            vr(a, reg_of(&inst.srcs[1])),
            spair(a, reg_of(&inst.srcs[0])),
            if inst.imm == 0 { String::new() } else { format!(" offset:{}", inst.imm) }
        )],
        MOp::GlobalLoadB128 => vec![format!(
            "global_load_dwordx4 {}, {}",
            tuple(a, inst.dst.expect("dst"), 4),
            mem_op(a, inst.srcs[0], inst.imm)
        )],
        MOp::GlobalLoadLdsB128 | MOp::GlobalLoadLdsB32 => {
            let m0 = sr(a, reg_of(&inst.srcs[1]));
            let mn = if inst.op == MOp::GlobalLoadLdsB128 { "global_load_lds_dwordx4" } else { "global_load_lds_dword" };
            vec![
                format!("s_mov_b32 m0, {m0}"),
                "s_nop 0".to_string(),
                format!("{mn} {}", mem_op(a, inst.srcs[0], inst.imm)),
            ]
        }
        MOp::GlobalStoreU16 => vec![format!(
            "global_store_short {}, {}, off{}",
            pair(a, reg_of(&inst.srcs[0])),
            vr(a, reg_of(&inst.srcs[1])),
            if inst.imm == 0 { String::new() } else { format!(" offset:{}", inst.imm) }
        )],
        MOp::GlobalStoreF32 => vec![format!(
            "global_store_dword {}, {}, off{}",
            pair(a, reg_of(&inst.srcs[0])),
            vr(a, reg_of(&inst.srcs[1])),
            if inst.imm == 0 { String::new() } else { format!(" offset:{}", inst.imm) }
        )],
        MOp::SLoadDword => vec![format!("s_load_dword {}, s[0:1], {}", d_s(a, inst), inst.imm)],
        MOp::SLoadDwordx2 => {
            vec![format!("s_load_dwordx2 {}, s[0:1], {}", spair(a, inst.dst.unwrap()), inst.imm)]
        }
        MOp::SReadPhys => vec![format!("s_mov_b32 {}, s{}", d_s(a, inst), inst.imm)],
        MOp::SMovB32 => {
            let text = match inst.srcs.first() {
                Some(s) => src1_s(a, *s),
                None => format!("{}", inst.imm as i32),
            };
            vec![format!("s_mov_b32 {}, {}", d_s(a, inst), text)]
        }
        MOp::SAddU32 => vec![format!(
            "s_add_u32 {}, {}, {}",
            d_s(a, inst),
            src1_s(a, inst.srcs[0]),
            src1_s(a, inst.srcs[1])
        )],
        MOp::SAddcU32 => vec![format!(
            "s_addc_u32 {}, {}, {}",
            d_s(a, inst),
            src1_s(a, inst.srcs[0]),
            src1_s(a, inst.srcs[1])
        )],
        MOp::SMulI32 => vec![format!(
            "s_mul_i32 {}, {}, {}",
            d_s(a, inst),
            src1_s(a, inst.srcs[0]),
            src1_s(a, inst.srcs[1])
        )],
        MOp::SShlB32 => vec![format!(
            "s_lshl_b32 {}, {}, {}",
            d_s(a, inst),
            src1_s(a, inst.srcs[0]),
            src1_s(a, inst.srcs[1])
        )],
        MOp::SCmpLtI32 => vec![format!(
            "s_cmp_lt_i32 {}, {}",
            src1_s(a, inst.srcs[0]),
            src1_s(a, inst.srcs[1])
        )],
        MOp::SNop => vec![format!("s_nop {}", inst.imm)],
        MOp::SWaitVm => vec![format!("s_waitcnt vmcnt({})", inst.imm)],
        MOp::SWaitLgkm => vec![format!("s_waitcnt lgkmcnt({})", inst.imm)],
        MOp::LdsWriteB32 => vec![format!(
            "ds_write_b32 {}, {}{}",
            src1(a, inst.srcs[0]),
            src1(a, inst.srcs[1]),
            lds_off(inst.imm)
        )],
        MOp::LdsReadB32 => vec![format!("ds_read_b32 {}, {}{}", d(a), src1(a, inst.srcs[0]), lds_off(inst.imm))],
        MOp::LdsWriteB128 => vec![format!(
            "ds_write_b128 {}, {}{}",
            src1(a, inst.srcs[0]),
            tuple(a, reg_of(&inst.srcs[1]), 4),
            lds_off(inst.imm)
        )],
        MOp::LdsReadB128 => vec![format!(
            "ds_read_b128 {}, {}{}",
            tuple(a, inst.dst.expect("dst"), 4),
            src1(a, inst.srcs[0]),
            lds_off(inst.imm)
        )],
        MOp::LdsReadB64TrB8 => vec![format!(
            "ds_read_b64_tr_b8 {}, {}{}",
            tuple(a, inst.dst.expect("dst"), 2),
            src1(a, inst.srcs[0]),
            lds_off(inst.imm)
        )],
        MOp::VReadFirstLane => {
            vec![format!("v_readfirstlane_b32 {}, {}", sr(a, inst.dst.expect("dst")), src1(a, inst.srcs[0]))]
        }
        MOp::SBarrier => vec!["s_barrier".to_string()],
        MOp::SSetPrio => vec![format!("s_setprio {}", inst.imm)],
        MOp::SEndpgm => vec!["s_endpgm".to_string()],
    }
}

fn reg_of(s: &Src) -> VReg {
    match s {
        Src::Reg(r) => *r,
        Src::Imm(_) => 0,
    }
}

fn d_s(a: &Alloc, inst: &MInst) -> String {
    sr(a, inst.dst.expect("dst"))
}

fn bin(a: &Alloc, inst: &MInst, mnemonic: &str) -> Vec<String> {
    vec![format!(
        "{} {}, {}, {}",
        mnemonic,
        vr(a, inst.dst.unwrap()),
        src1(a, inst.srcs[0]),
        src1(a, inst.srcs[1])
    )]
}

fn un(a: &Alloc, inst: &MInst, mnemonic: &str) -> Vec<String> {
    vec![format!("{} {}, {}", mnemonic, vr(a, inst.dst.unwrap()), src1(a, inst.srcs[0]))]
}

fn cmp(a: &Alloc, inst: &MInst, mnemonic: &str) -> Vec<String> {
    vec![format!("{} vcc, {}, {}", mnemonic, src1(a, inst.srcs[0]), src1(a, inst.srcs[1]))]
}

/// ` offset:N` suffix of a DS instruction (empty for offset 0).
fn lds_off(imm: i64) -> String {
    if imm == 0 {
        String::new()
    } else {
        format!(" offset:{imm}")
    }
}
