import collections,sys
def fmt(b):  # b: bytes of the instruction
    d0=int.from_bytes(b[:4],'little')
    top9=d0>>23; top6=d0>>26; top8=d0>>24
    if top9==0x17D: return 'SOP1',(d0>>8)&0xff
    if top9==0x17E: return 'SOPC',(d0>>16)&0x7f
    if top9==0x17F: return 'SOPP',(d0>>16)&0x7f
    if (d0>>28)==0xB: return 'SOPK',(d0>>23)&0x1f
    if (d0>>30)==2: return 'SOP2',(d0>>23)&0x7f
    if top6==0x30: return 'SMEM',(d0>>18)&0xff
    if (d0>>25)==0x3F: return 'VOP1',(d0>>9)&0xff
    if (d0>>25)==0x3E: return 'VOPC',(d0>>17)&0xff
    if (d0>>31)==0: return 'VOP2',(d0>>25)&0x3f
    if top6==0x34: return 'VOP3',(d0>>16)&0x3ff
    if top6==0x33: return 'VOP3P',(d0>>16)&0x7f
    if top6==0x36: return 'DS',(d0>>18)&0xff
    if top6==0x38: return 'MUBUF',(d0>>18)&0x7f
    if top6==0x3a: return 'MTBUF',(d0>>16)&0xf
    if top6==0x37: 
        seg=(d0>>14)&3
        return ('FLAT','SCRATCH','GLOBAL','?')[seg],(d0>>18)&0x7f
    return 'UNK',d0>>26
tab=collections.defaultdict(lambda: collections.Counter())
sizes=collections.defaultdict(collections.Counter)
for l in open('/tmp/oracle.tsv'):
    a,h=l.rstrip('\n').split('\t'); b=bytes.fromhex(h)
    mn=a.split()[0]
    tab[mn][fmt(b)]+=1; sizes[mn][len(b)]+=1
amb=[(m,dict(c)) for m,c in tab.items() if len(c)>1]
print('mnemonics',len(tab),'ambiguous',len(amb))
for m,c in amb[:40]: print(' AMB',m,c, dict(sizes[m]))
unk=[(m,dict(c)) for m,c in tab.items() if any(k[0]=='UNK' for k in c)]
print('unknown format',unk[:10])
fm=collections.Counter(next(iter(c))[0] for c in tab.values()); print(fm)
out=['//! GENERATED by tools/gen_enc_tables.py from the llvm-mc oracle (opcode and format of every mnemonic the compiler emits). Do not edit.','']
out.append('pub static OPS: &[(&str, &str, u16)] = &[')
for m in sorted(tab):
    f,o=tab[m].most_common(1)[0][0]
    out.append('    (%r, %r, %d),'%(m,f,o))
out.append('];')
open('/tmp/enc_tables.rs','w').write('\n'.join(out).replace("'",'"')+'\n')
